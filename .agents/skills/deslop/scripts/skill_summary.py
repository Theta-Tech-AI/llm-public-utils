#!/usr/bin/env python3
"""Keep the three summary levels of the skill in step: the frontmatter description (L0), SKILL.md (L1), references/ (L2).

Only SKILL.md loads when the skill activates and only its frontmatter is always in context, so the principles reach a
reader through summaries. L2 owns the text; the "library at a glance" block in SKILL.md is generated from L2's own
`description:` lines and `lenses.json`, so it cannot drift by hand-editing.

    python3 scripts/skill_summary.py           # regenerate the block between the markers, in place
    python3 scripts/skill_summary.py --check   # exit 1 when the block is stale, the description is over the limit,
                                               # or SKILL.md links a file that does not exist
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL = ROOT / "SKILL.md"
REF = ROOT / "references"
START, END = "<!-- principle-map:start -->", "<!-- principle-map:end -->"
LIMIT = 1024  # the Agent Skills limit on a frontmatter description
LINK = re.compile(r"\]\(([^)\s#]+?\.md)(?:#[^)]*)?\)")
DESC = re.compile(r"^description: Deslop (?:principle|pattern) — (.+)$", re.M)


def split(rel: str) -> tuple[str, str]:
    """The `Name: essence` description line, split at its last `: ` (a name may hold a colon, an essence may not)."""
    m = DESC.search((REF / rel).read_text())
    if not m:
        sys.exit(f"FAIL {rel}: no `description: Deslop principle|pattern — Name: essence.` line")
    head, sep, tail = m.group(1).rstrip(".").rpartition(": ")
    if not sep:
        sys.exit(f"FAIL {rel}: description is not `Name: essence`")
    return head, tail


def short(essence: str, cap: int = 110) -> str:
    """The first clause of a long essence (cut at `; ` or ` — `), word-trimmed if still over the cap: the full text is one click away."""
    if len(essence) > cap:
        essence = re.split(r"; | — ", essence)[0]
    if len(essence) > cap:
        essence = essence[:cap].rsplit(" ", 1)[0] + "…"
    return essence


def entry(rel: str) -> str:
    name, essence = split(rel)
    essence = short(essence)
    return f"- [{name}](references/{rel}) — {essence}"


def block() -> str:
    lenses = json.loads((REF / "lenses.json").read_text())["lenses"]
    carriers: dict[str, list[str]] = {}
    out = [START, "<!-- generated by scripts/skill_summary.py from the references' description lines; do not edit -->", ""]
    for lens, spec in lenses.items():
        out += [f"**{lens}** — {spec['stance']}", ""]
        out += [entry(f) for f in spec["files"]] + [""]
        for p in spec.get("patterns", []):
            carriers.setdefault(p, []).append(lens)
    out += ["**patterns** — recurring shapes that span principles; never charged by themselves, each instance is filed under the owning principle", ""]
    for p, ls in carriers.items():
        out.append(f"{entry(p)} *(read in: {', '.join(ls)})*")
    return "\n".join(out + ["", END])


def frontmatter_description(text: str) -> str:
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    d = re.search(r'^description: (".*")$', m.group(1) if m else "", re.M)
    if not d:
        sys.exit("FAIL SKILL.md: frontmatter has no double-quoted `description:` line")
    return json.loads(d.group(1))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    check = ap.parse_args().check
    text = SKILL.read_text()
    if START not in text or END not in text:
        sys.exit(f"FAIL SKILL.md: markers {START} / {END} missing")
    pre, rest = text.split(START, 1)
    fresh = pre + block() + rest.split(END, 1)[1]
    if not check:
        SKILL.write_text(fresh)
        text = fresh
    problems = []
    if fresh != text:
        problems.append("the generated principle map is stale: run `python3 scripts/skill_summary.py`")
    n = len(frontmatter_description(text))
    if n > LIMIT:
        problems.append(f"frontmatter description is {n} characters, over the {LIMIT} limit")
    for target in sorted(set(LINK.findall(text))):
        if not (ROOT / target).is_file():
            problems.append(f"SKILL.md links a file that does not exist: {target}")
    for p in problems:
        print("FAIL", p, file=sys.stderr)
    print(f"description {n}/{LIMIT} chars; SKILL.md {len(text.encode())} bytes")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
